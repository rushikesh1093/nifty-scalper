"""
Markdown tables from a research output directory, so report numbers are
generated, never retyped.

    python -m app.research.report <out_dir>   → writes <out_dir>/tables.md
"""
from __future__ import annotations

import csv
import json
import sys
from collections import defaultdict
from pathlib import Path

from app.research import metrics

BASE = {"FIRST_CANDLE_BREAKOUT": "FCB_BASE", "ORB_BREAKOUT": "ORB_BASE",
        "SUPERTREND_EMA": "ST_BASE", "EMA_RSI_PULLBACK_15M": "ER_BASE", "PIVOT_BOUNCE": "PV_BASE"}


def _f(x, nd=3):
    if x is None:
        return "–"
    if isinstance(x, (list, tuple)):
        return "[" + ", ".join(_f(v, nd) for v in x) + "]"
    if isinstance(x, float):
        return f"{x:+.{nd}f}" if nd == 3 else f"{x:.{nd}f}"
    return str(x)


def _table(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def build(out_dir: str) -> str:
    d = Path(out_dir)
    s = json.loads((d / "summary.json").read_text())
    wf = json.loads((d / "walk_forward.json").read_text())
    man = json.loads((d / "manifest.json").read_text())
    parts = [f"<!-- generated by app.research.report from {d.name}, commit {man['commit'][:10]} -->"]

    # A. signal quality
    rows = []
    for vid, e in s["variants"].items():
        q = e["signal_quality"]
        z = e["ZERO"]["post_design"]
        rows.append([vid, q["n"], _f(q.get("directional_hit_30m"), 2), _f(q.get("hit_1r_before_stop"), 2),
                     _f(q.get("hit_2r_before_stop"), 2), _f(q.get("stop_first"), 2),
                     _f(q.get("median_mfe_eod_r"), 2), _f(q.get("median_mae_eod_r"), 2),
                     q.get("median_min_to_1r"), q.get("median_min_to_stop"),
                     _f(e["ZERO"]["all"].get("expectancy_r")), _f(z.get("expectancy_r")),
                     _f(z.get("expectancy_ci95")), q.get("ambiguous_candles")])
    parts.append("### Experiment A — underlying signal quality (all sessions; R before any cost)\n\n" + _table(
        ["variant", "n", "dir 30m", "1R before stop", "2R before stop", "stop first", "med MFE→15:15",
         "med MAE→15:15", "min to 1R", "min to stop", "exp R (all)", "exp R post-design",
         "post-design CI95", "ambiguous"], rows))

    # costs
    rows = []
    for vid, e in s["variants"].items():
        r = [vid, e["MEASURED"]["post_design"].get("n")]
        for cm in ("ZERO", "MEASURED", "HARSH"):
            p = e[cm]["post_design"]
            r += [_f(p.get("expectancy_r")), _f(p.get("profit_factor"), 2)]
        r.append(_f(e["MEASURED"]["post_design"].get("mean_cost_r")))
        rows.append(r)
    parts.append("### Net expectancy by cost model (post-design window, fixed variant, no selection)\n\n" + _table(
        ["variant", "n", "ZERO exp", "ZERO PF", "MEASURED exp", "MEASURED PF", "HARSH exp", "HARSH PF",
         "mean cost R"], rows))

    # full metrics, primary cost
    rows = []
    for vid, e in s["variants"].items():
        p = e["MEASURED"]["post_design"]
        rows.append([vid, p.get("n"), p.get("sessions"), _f(p.get("win_rate"), 2), _f(p.get("win_rate_ci95")),
                     _f(p.get("profit_factor"), 2), _f(p.get("expectancy_r")), _f(p.get("expectancy_ci95")),
                     _f(p.get("avg_win_r"), 2), _f(p.get("avg_loss_r"), 2), _f(p.get("payoff"), 2),
                     _f(p.get("max_drawdown_r"), 1), p.get("max_consecutive_losses"),
                     _f(p.get("sharpe_daily_ann"), 2), _f(p.get("sortino_daily_ann"), 2),
                     _f(p.get("mean_mfe_r"), 2), _f(p.get("mean_mae_r"), 2), _f(p.get("mean_hold_min"), 0)])
    parts.append("### Performance, MEASURED costs, post-design window\n\n" + _table(
        ["variant", "n", "sessions", "win%", "win CI95", "PF", "exp R", "exp CI95 (session bootstrap)",
         "avg win", "avg loss", "payoff", "max DD R", "max consec L", "Sharpe(d)", "Sortino(d)",
         "MFE", "MAE", "hold min"], rows))

    # breakdowns for baselines
    bases = s.get("base_variants") or list(BASE.values())
    for vid in bases:
        strat = s["variants"][vid]["strategy"]
        b = s["variants"][vid]["breakdowns_post_design"]
        lines = []
        for dim in ("side", "regime", "vol", "trend_align", "time_of_day", "weekday", "expiry",
                    "exit_reason", "pivot_level"):
            for k, v in b.get(dim, {}).items():
                if k in ("None",) or not v.get("n"):
                    continue
                lines.append([dim, k, v["n"], _f(v.get("win_rate"), 2), _f(v.get("expectancy_r")),
                              _f(v.get("expectancy_ci95")), _f(v.get("profit_factor"), 2)])
        parts.append(f"#### {strat} ({vid}) breakdowns, MEASURED costs, post-design\n\n" + _table(
            ["dimension", "bucket", "n", "win%", "exp R", "CI95", "PF"], lines))

    # exit variants
    rows = []
    for vid, ev in s["exit_variants"].items():
        for name, e in sorted(ev.items()):
            dz, pz, pm = e["ZERO"]["design"], e["ZERO"]["post_design"], e["MEASURED"]["post_design"]
            rows.append([vid, name, pz.get("n"), _f(dz.get("expectancy_r")), _f(pz.get("expectancy_r")),
                         _f(pm.get("expectancy_r")), _f(pm.get("expectancy_ci95")),
                         _f(pm.get("profit_factor"), 2), _f(pm.get("max_drawdown_r"), 1),
                         _f(pm.get("mean_hold_min"), 0)])
    parts.append("### Exit variants on identical baseline entries\n\n" + _table(
        ["entries", "exit", "n post", "ZERO design", "ZERO post", "MEASURED post", "MEASURED CI95",
         "PF", "max DD R", "hold min"], rows))

    # walk-forward
    rows = []
    for strat, by_cost in wf["strategies"].items():
        for cm, r in by_cost.items():
            o = r["oos"]
            rows.append([strat, cm, r["status"], o.get("n"), o.get("sessions"), _f(o.get("expectancy_r")),
                         _f(o.get("expectancy_ci95")), _f(o.get("profit_factor"), 2),
                         f"{r['folds_traded']}/{r['folds_total']}", r["folds_positive"],
                         _f(r.get("worst_fold_r"), 2), _f(r.get("best_fold_r"), 2), _f(r.get("fold_r_std"), 2)])
    parts.append("### Walk-forward out-of-sample (selection on train, gate on validation)\n\n" + _table(
        ["strategy", "costs", "status", "OOS n", "sessions", "OOS exp R", "CI95", "PF",
         "months traded", "months +", "worst month R", "best month R", "month R sd"], rows))
    rows = []
    for strat, by_cost in wf["strategies"].items():
        choices = defaultdict(int)
        for f in by_cost["MEASURED"]["folds"]:
            choices[f["choice"]] += 1
        rows.append([strat, ", ".join(f"{k}×{v}" for k, v in sorted(choices.items(), key=lambda kv: -kv[1]))])
    parts.append("### Walk-forward choices per test month (MEASURED)\n\n" + _table(["strategy", "choices"], rows))

    # option replay
    p = d / "option_replay.csv"
    if p.exists() and p.stat().st_size:
        rep = list(csv.DictReader(p.open(encoding="utf-8")))
        rows = []
        grp = defaultdict(list)
        for r in rep:
            grp[(r["variant"], r["otm_steps"])].append(r)
        for (vid, k), rs in sorted(grp.items()):
            fl = [r for r in rs if r["status"] == "FILLED"]
            rows.append([vid, "ATM" if k == "0" else "OTM1", len(rs), len(fl),
                         _f(sum(float(r["spot_r_gross"]) for r in fl) / len(fl), 2) if fl else "–",
                         round(sum(float(r["gross_rs"]) for r in fl)), round(sum(float(r["charges_rs"]) for r in fl)),
                         round(sum(float(r["spread_cost_rs"]) for r in fl)), round(sum(float(r["net_rs"]) for r in fl))])
        parts.append("### Experiment B — recorded-quote option replay of the same trades\n\n" + _table(
            ["variant", "contract", "trades on quoted days", "filled", "spot R (filled)", "gross Rs",
             "charges Rs", "spread cost Rs", "net Rs"], rows))
    return "\n\n".join(parts) + "\n"


if __name__ == "__main__":
    out = Path(sys.argv[1])
    (out / "tables.md").write_text(build(str(out)), encoding="utf-8")
    print(out / "tables.md")
